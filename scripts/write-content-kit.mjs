/**
 * Concatenate content/*.json into content/kit.js as window.ShantaraContent.
 * JSON remains the source of truth; regenerate after editing records.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const contentDir = path.join(root, "content");
const outFile = path.join(contentDir, "kit.js");

function readJsonFiles(dir) {
  if (!fs.existsSync(dir)) return [];
  return fs
    .readdirSync(dir)
    .filter((f) => f.endsWith(".json"))
    .sort()
    .map((f) => JSON.parse(fs.readFileSync(path.join(dir, f), "utf8")));
}

function readJson(file) {
  const p = path.join(contentDir, file);
  if (!fs.existsSync(p)) return null;
  return JSON.parse(fs.readFileSync(p, "utf8"));
}

const payload = {
  site: readJson("site.json"),
  tariff: readJson("tariff.json"),
  medicalCategories: readJson("medical-categories.json"),
  programs: readJsonFiles(path.join(contentDir, "programs")),
  conditions: readJsonFiles(path.join(contentDir, "conditions")),
  therapies: readJsonFiles(path.join(contentDir, "therapies")),
  rooms: readJsonFiles(path.join(contentDir, "rooms")),
  doctors: readJsonFiles(path.join(contentDir, "doctors")),
  leadership: readJsonFiles(path.join(contentDir, "leadership")),
  articles: readJsonFiles(path.join(contentDir, "articles")),
  doctorAnswers: readJsonFiles(path.join(contentDir, "doctor-answers")),
  faq: readJson("faq.json"),
  guestStories: readJsonFiles(path.join(contentDir, "guest-stories")),
  events: readJsonFiles(path.join(contentDir, "events")),
  testimonials: readJsonFiles(path.join(contentDir, "testimonials")),
};

const banner = `/* Generated by scripts/write-content-kit.mjs -- do not edit by hand.
 * Source: JSON files under content/
 */
`;

const body = `${banner}window.ShantaraContent = ${JSON.stringify(payload, null, 2)};
`;

fs.writeFileSync(outFile, body);
console.log(`Wrote ${path.relative(root, outFile)} (${Buffer.byteLength(body)} bytes)`);
